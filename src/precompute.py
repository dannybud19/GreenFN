"""Phase 6 precompute (notes/phase6_plan.md, sections 2 to 5).

Builds everything the app (Phase 7) needs from the final model, writes it to exports/, and writes the
Phase 6 report with the checks on it.

Final model: seed 2026 of the Phase 5 chosen pipeline
    Phase 3 encoder (lambda 0 control, models/phase4/adversary_lambda0.0_s2026.pt)
    -> season centring alpha 0.5 (Phase 4)
    -> career score, centre 0.25, peak 0.75, lambda 0 (Phase 5)

    python precompute.py [--quick]

Exports (exports/, git-ignored, regenerated by this script):
    players.json        one entry per player: name, seasons, decade, spread and its percentile
    comps.json          top 10 career comps per player (lambda 0, the default)
    why.json            per-feature "why similar" breakdown for each player's top 5 comps
    seasons_umap.csv    2D map coordinates for every season (for the map and career trajectory lines)
    profiles.npz        centre, peak and spread vectors plus the score scales, so the API can apply the
                        lambda slider live
    manifest.json       model provenance, settings, counts and a SHA-256 for every file

Hold-outs are excluded until final evaluation. Nothing is trained.
"""

import argparse
import hashlib
import json
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
import umap
from sklearn.manifold import trustworthiness

from baselines import STYLE
from career import CareerScore, build_profiles, scales, top_k
from era_adversary import SeasonCentred
from evaluate_era import load_adv, splits
from explain import DifferentiableCareer, deletion_test, explain_pair, player_inputs

ROOT = Path(__file__).resolve().parents[1]
EXPORTS = ROOT / "exports"
REPORT = ROOT / "reports" / "phase6_explain.md"

SEED = 2026
CENTRING_ALPHA = 0.5
ALPHA, BETA, LAMBDA = 0.25, 0.75, 0.0
N_COMPS, N_WHY = 10, 5
UMAP_PARAMS = {"n_neighbors": 15, "min_dist": 0.1, "metric": "cosine", "random_state": 2026}
DELETION_PAIRS = 300
TRUST_SAMPLE = 3000
EXAMPLE_PAIRS = [("jordami01", "bryanko01"), ("onealsh01", "howardw01"), ("rodmade01", "evansre01"),
                 ("stockjo01", "paulch01"), ("nashst01", "pricema01")]


def check_chosen_setting() -> None:
    text = (ROOT / "reports" / "phase5_career.md").read_text()
    if f"Chosen: Career a={ALPHA} b={BETA} lambda={LAMBDA}" not in text:
        raise ValueError("Phase 5 report's chosen setting doesn't match precompute.py constants")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main(quick: bool) -> None:
    t0 = time.time()
    check_chosen_setting()
    df, train, _, _, pool = splits()
    pool = pool.reset_index(drop=True)
    base = load_adv(0.0, SEED)
    model = SeasonCentred(base, CENTRING_ALPHA).fit(train)

    # ---- profiles and comps ----
    profs = build_profiles(model, pool, min_seasons=1)
    sc = scales(build_profiles(model, train, min_seasons=2))
    method = CareerScore(ALPHA, BETA, LAMBDA, sc)
    tops = top_k(method, profs, profs, N_COMPS)
    smat = method.matrix(profs, profs)
    idx = {p.player_id: i for i, p in enumerate(profs)}
    long_spreads = np.array([p.spread for p in profs if len(p.emb) >= 4])
    print(f"{len(profs)} players, {len(pool)} seasons; comps done ({time.time() - t0:.0f}s)")

    # ---- why similar ----
    diff = DifferentiableCareer(base.model, model.means, CENTRING_ALPHA, ALPHA, BETA, sc)
    inputs = {p.player_id: player_inputs(pool, p.player_id) for p in profs}
    who = profs[:40] if quick else profs
    why, errors = {}, []
    for n, p in enumerate(who, start=1):
        why[p.player_id] = {}
        for j in tops[idx[p.player_id]][:N_WHY]:
            c = profs[j]
            ex = explain_pair(diff, inputs[p.player_id], inputs[c.player_id])
            why[p.player_id][c.player_id] = {k: round(v, 5) for k, v in ex["per_feature"].items()}
            errors.append(ex["completeness_error"])
        if n % 500 == 0:
            print(f"  explained {n}/{len(who)} players ({time.time() - t0:.0f}s)")
    errors = np.array(errors)
    print(f"why-similar done for {len(who)} players; completeness error mean {errors.mean():.4%}, "
          f"max {errors.max():.4%} ({time.time() - t0:.0f}s)")

    # ---- faithfulness: deletion test on a fixed random sample of (player, top-5 comp) pairs ----
    rng = np.random.default_rng(SEED)
    pairs = [(p.player_id, c) for p in who for c in why[p.player_id]]
    sample = [pairs[i] for i in rng.choice(len(pairs), min(DELETION_PAIRS if not quick else 30, len(pairs)), replace=False)]
    drops = []
    for a, b in sample:
        ex = explain_pair(diff, inputs[a], inputs[b])
        a_side = dict(zip(STYLE, ex["attr_a"].sum(0).tolist()))
        drops.append(deletion_test(diff, inputs[a], inputs[b], a_side))
    drops = np.array(drops)
    print(f"deletion test: top-3 drop {drops[:, 0].mean():.3f} vs random {drops[:, 1].mean():.3f} "
          f"({time.time() - t0:.0f}s)")

    # ---- map ----
    emb = model.embed(pool)
    coords = umap.UMAP(**UMAP_PARAMS).fit_transform(emb)
    s = rng.choice(len(emb), min(TRUST_SAMPLE, len(emb)), replace=False)
    trust = float(trustworthiness(emb[s], coords[s], n_neighbors=10, metric="cosine"))
    print(f"UMAP done; trustworthiness {trust:.3f} ({time.time() - t0:.0f}s)")

    # ---- exports ----
    EXPORTS.mkdir(exist_ok=True)
    players = [{"player_id": p.player_id, "player": p.player, "first_season": int(p.seasons.min()),
                "last_season": int(p.seasons.max()), "n_seasons": int(len(p.seasons)), "decade": p.decade,
                "spread": round(p.spread, 5),
                "spread_percentile": round(float((long_spreads < p.spread).mean()), 4) if len(p.emb) >= 4 else None}
               for p in profs]
    comps = {p.player_id: [{"player_id": profs[j].player_id, "rank": r + 1, "score": round(float(smat[i, j]), 4)}
                           for r, j in enumerate(tops[i])] for i, p in enumerate(profs)}
    (EXPORTS / "players.json").write_text(json.dumps(players, ensure_ascii=False))
    (EXPORTS / "comps.json").write_text(json.dumps(comps))
    (EXPORTS / "why.json").write_text(json.dumps(why))
    pd.DataFrame({"player_id": pool["player_id"], "season": pool["season"], "x": coords[:, 0].round(4),
                  "y": coords[:, 1].round(4)}).to_csv(EXPORTS / "seasons_umap.csv", index=False)
    np.savez_compressed(EXPORTS / "profiles.npz", player_id=np.array([p.player_id for p in profs]),
                        centre=np.stack([p.centre for p in profs]), peak=np.stack([p.peak for p in profs]),
                        spread=np.array([p.spread for p in profs]),
                        scales=np.array([sc["centre"], sc["peak"], sc["spread"]]))
    files = ["players.json", "comps.json", "why.json", "seasons_umap.csv", "profiles.npz"]
    manifest = {
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "model": {"encoder": f"models/phase4/adversary_lambda0.0_s{SEED}.pt", "centring_alpha": CENTRING_ALPHA,
                  "career_score": {"alpha": ALPHA, "beta": BETA, "lambda": LAMBDA}, "scales": sc},
        "umap": UMAP_PARAMS, "quick": quick,
        "counts": {"players": len(profs), "seasons": int(len(pool)), "players_explained": len(who)},
        "files": {f: {"bytes": (EXPORTS / f).stat().st_size, "sha256": sha256(EXPORTS / f)} for f in files},
    }
    (EXPORTS / "manifest.json").write_text(json.dumps(manifest, indent=2))

    # ---- coverage ----
    seasons_with_coords = len(pool) == len(coords) and not np.isnan(coords).any()
    coverage = {
        "players with 10 comps": sum(len(v) == N_COMPS for v in comps.values()),
        "players with why-similar for their top 5": sum(len(why.get(p.player_id, {})) == min(N_WHY, N_COMPS) for p in profs),
        "seasons with map coordinates": int(len(coords)) if seasons_with_coords else 0,
    }

    # ---- examples ----
    examples = []
    for a, b in EXAMPLE_PAIRS:
        if a in idx and b in idx:
            ex = explain_pair(diff, inputs[a], inputs[b])
            top3 = sorted(ex["per_feature"].items(), key=lambda kv: -kv[1])[:3]
            low = min(ex["per_feature"].items(), key=lambda kv: kv[1])
            rank = next((r + 1 for r, j in enumerate(np.argsort(-np.where(np.arange(len(profs)) == idx[a], -np.inf, smat[idx[a]])))
                         if j == idx[b]), None)
            examples.append((profs[idx[a]].player, profs[idx[b]].player, rank, top3, low))

    write_report(len(profs), len(pool), len(who), quick, errors, drops, trust, coverage, examples, manifest,
                 time.time() - t0)
    print(f"Wrote {EXPORTS} and {REPORT} in {time.time() - t0:.0f}s")


def write_report(n_players, n_seasons, n_explained, quick, errors, drops, trust, coverage, examples, manifest, secs):
    top_better = float((drops[:, 0] > drops[:, 1]).mean())
    lines = [
        "# Phase 6 results: explanations, map and precompute", "",
        f"Final model: Phase 5's chosen pipeline, seed {SEED} (encoder, season centring alpha {CENTRING_ALPHA}, "
        f"career score centre {ALPHA} / peak {BETA} / lambda {LAMBDA}). Hold-outs excluded. "
        f"{'QUICK RUN: only 40 players explained.' if quick else ''}", "",
        "## Coverage", "",
        "| Item | Count | Of |", "|---|---|---|",
        f"| Players with 10 comps | {coverage['players with 10 comps']:,} | {n_players:,} |",
        f"| Players with a why-similar breakdown for their top 5 | {coverage['players with why-similar for their top 5']:,} | {n_players:,} |",
        f"| Seasons with map coordinates | {coverage['seasons with map coordinates']:,} | {n_seasons:,} |", "",
        "## Why similar: integrated gradients checks", "",
        f"Explanations computed: {len(errors):,} pairs ({n_explained:,} players x top {N_WHY}).", "",
        "| Check | Result |", "|---|---|",
        f"| Completeness error (attributions vs score change), mean | {errors.mean():.3%} |",
        f"| Completeness error, max | {errors.max():.3%} |",
        f"| Pairs with completeness error under 1% | {int((errors < 0.01).sum()):,} of {len(errors):,} ({(errors < 0.01).mean():.2%}) |",
        f"| Deletion test: mean score drop, top-3 credited features set to average | {drops[:, 0].mean():.3f} |",
        f"| Deletion test: mean score drop, 3 random features | {drops[:, 1].mean():.3f} |",
        f"| Pairs where the top 3 matter more than random | {top_better:.1%} (of {len(drops)}) |", "",
        "## Example breakdowns (top 3 features making them alike; the feature pulling them apart most)", "",
        "| Player | Comp | Comp's rank | Most alike on | Least alike on |", "|---|---|---|---|---|",
    ]
    for a, b, rank, top3, low in examples:
        lines.append(f"| {a} | {b} | {rank if rank else 'n/a'} | "
                     f"{', '.join(f'{k} ({v:+.2f})' for k, v in top3)} | {low[0]} ({low[1]:+.2f}) |")
    lines += ["", "## Map", "",
              f"UMAP on every season's embedding ({', '.join(f'{k} {v}' for k, v in UMAP_PARAMS.items())}). "
              f"Trustworthiness (10 neighbours, {TRUST_SAMPLE:,}-season sample): **{trust:.3f}** (1.0 = every 2D "
              "neighbourhood is a real neighbourhood). The map is for display only: comps are always computed in "
              "the full embedding (feature note, check 6).", ""]
    gate = [
        ("Every player has 10 comps", coverage["players with 10 comps"] == n_players),
        ("Every player has a why-similar breakdown for his top 5", coverage["players with why-similar for their top 5"] == n_players),
        ("Every season has map coordinates", coverage["seasons with map coordinates"] == n_seasons),
        ("Completeness error under 1% on average", errors.mean() < 0.01),
        ("Deletion test: top-3 features matter more than random, on average and in at least 70% of pairs",
         drops[:, 0].mean() > drops[:, 1].mean() and top_better >= 0.70),
    ]
    lines += ["## Gate (phase6_plan.md section 6)", ""]
    lines += [f"- {'PASS' if ok else 'FAIL'}: {lab}" for lab, ok in gate]
    lines += ["", "If a line fails, it is recorded as a finding; the metric is not changed.", "",
              "## Exports (`exports/`, git-ignored; regenerate with `python src/precompute.py`)", "",
              "| File | Bytes | SHA-256 (first 16) |", "|---|---|---|"]
    lines += [f"| {f} | {v['bytes']:,} | {v['sha256'][:16]} |" for f, v in manifest["files"].items()]
    lines += ["", f"Run time: {secs / 60:.1f} minutes.", ""]
    REPORT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--quick", action="store_true", help="explain only 40 players (pipeline test)")
    main(p.parse_args().quick)
