"""Profile the raw per-100 and advanced tables and write notes/raw_data_inventory.md."""

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw"
OUT = ROOT / "notes" / "raw_data_inventory.md"
TABLES = ["Per 100 Poss.csv", "Advanced.csv"]


def to_ranges(seasons: list[int]) -> str:
    """[1950, 1951, 1952, 1960] -> '1950–1952, 1960'."""
    if not seasons:
        return ""
    out, start, prev = [], seasons[0], seasons[0]
    for s in seasons[1:]:
        if s != prev + 1:
            out.append(f"{start}–{prev}" if start != prev else f"{start}")
            start = s
        prev = s
    out.append(f"{start}–{prev}" if start != prev else f"{start}")
    return ", ".join(out)


def profile(path: Path) -> str:
    df = pd.read_csv(path)
    seasons = sorted(df["season"].unique())
    lines = [
        f"## {path.name}",
        "",
        f"- Rows: {len(df):,} · Columns: {df.shape[1]}",
        f"- Seasons: {seasons[0]}–{seasons[-1]} ({len(seasons)} seasons)",
    ]
    if "lg" in df:
        by_lg = df.groupby("lg")["season"].agg(["min", "max", "size"])
        lgs = "; ".join(f"{lg} {r['min']}–{r['max']} ({r['size']:,} rows)" for lg, r in by_lg.iterrows())
        lines.append(f"- Leagues: {lgs}")
    lines += [
        "",
        "Empty seasons = seasons in which the column is null for every row of that league.",
        "",
        "| Column | dtype | Null % | Empty seasons (by league) |",
        "|---|---|---:|---|",
    ]
    all_null = df.isna().groupby([df["lg"], df["season"]]).all()
    for col in df.columns:
        parts = []
        for lg, flags in all_null[col].groupby(level="lg"):
            empty = [int(s) for (_, s), is_empty in flags.items() if is_empty]
            if empty:
                parts.append(f"{lg} {to_ranges(empty)}")
        lines.append(f"| `{col}` | {df[col].dtype} | {df[col].isna().mean():.1%} | {'; '.join(parts) or '—'} |")
    return "\n".join(lines)


def main() -> None:
    sections = [
        "# Raw data inventory",
        "",
        "Generated by `src/inspect_raw.py` from the Kaggle `sumitrodatta/nba-aba-baa-stats` dataset.",
    ]
    for name in TABLES:
        sections += ["", profile(RAW_DIR / name)]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(sections) + "\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
